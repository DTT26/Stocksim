const names = ['Apprentice', 'Rising Talent', 'Professional', 'Elite', 'Master', 'Legend'];

export function useChallengeTranslation() {
  const { lang: language } = useI18n();
  const tr = (text: string): string => {
    if (language !== 'en') return text;
    return english[text] ?? text
      .replace('Vi phạm Giới Hạn Lỗ Trong Ngày', 'Daily loss limit breached')
      .replace('Vi phạm Mức Sụt Giảm Tối Đa', 'Maximum drawdown breached')
      .replace('Giới hạn', 'Limit')
      .replace('Cấp độ thử thách không hợp lệ', 'Invalid challenge level')
      .replace(/Bạn cần vượt qua Level (\d+) để mở khóa Level này/, 'Pass Level $1 to unlock this level')
      .replace(/Bạn đã dùng hết (\d+) lượt reset trong tuần! Vui lòng chờ (\d+) ngày nữa để hồi lượt\./, 'You have used all $1 resets this week! Please wait $2 days for resets to refresh.');
  };
  return {
    tr,
    levelName: (id: number, fallback: string) => language === 'en' ? (names[id - 1] ?? fallback) : fallback,
    badge: (id: number) => `${language === 'en' ? 'Level' : 'Cấp'} ${id}`,
  };
}
